const { spawn, execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { EventEmitter } = require('events');

/**
 * OpenVPN 适配器 — 用 OpenVPN 的 TAP 驱动创建真实虚拟网卡
 *
 * 原理：
 *   - 主机模式：启动 OpenVPN server → 创建 TAP 网卡 → 分配 10.0.0.1
 *   - 客户端模式：启动 OpenVPN client → 连接主机 → 获取 10.0.0.x IP
 *   - 使用静态密钥（无需 CA 证书），P2P 场景最简单
 *
 * 要求：
 *   - 系统需安装 OpenVPN（默认路径 C:\Program Files\OpenVPN）
 *   - 或运行 wrtc-neo ovpn-install 自动下载安装
 */

const DEFAULT_OVPN_DIR = path.join(os.homedir(), '.wrtc-neo', 'ovpn');
const STATIC_KEY_FILE = path.join(DEFAULT_OVPN_DIR, 'static.key');
const CONFIG_DIR = path.join(DEFAULT_OVPN_DIR, 'configs');

// OpenVPN 可能安装路径
const OVPN_PATHS = [
    'C:\\Program Files\\OpenVPN\\bin\\openvpn.exe',
    'C:\\Program Files (x86)\\OpenVPN\\bin\\openvpn.exe',
    path.join(os.homedir(), 'OpenVPN\\bin\\openvpn.exe'),
    'openvpn' // 系统 PATH
];

class OvpnAdapter extends EventEmitter {
    constructor(options = {}) {
        super();
        this._subnet = options.subnet || '10.0.0';
        this._port = options.port || 1194;
        this._mode = 'none';       // 'server' | 'client' | 'none'
        this._process = null;
        this._state = 'stopped';
        this._localIP = null;
        this._remoteIP = null;
        this._configPath = null;
        this._staticKey = null;

        // 可自定义路径
        this._ovpnDir = options.ovpnDir || DEFAULT_OVPN_DIR;
        this._staticKeyFile = path.join(this._ovpnDir, 'static.key');
        this._configDir = path.join(this._ovpnDir, 'configs');

        // 确保目录存在
        [this._ovpnDir, this._configDir].forEach(d => {
            if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
        });
    }

    // ============================================================
    // 检测 OpenVPN
    // ============================================================
    static findOpenVPN() {
        for (const p of OVPN_PATHS) {
            if (fs.existsSync(p)) return p;
        }
        // 尝试 which
        try {
            const result = execSync('where openvpn 2>nul', { encoding: 'utf8', shell: 'cmd.exe' }).trim();
            if (result) return result.split('\n')[0].trim();
        } catch (e) { /* not found */ }
        return null;
    }

    static isInstalled() {
        return this.findOpenVPN() !== null;
    }

    static getTapDriverPath() {
        const tapDir = path.join(os.tmpdir(), 'wrtc-neo-tap');
        return {
            inf: path.join(tapDir, 'OemVista.inf'),
            sys: path.join(tapDir, 'tap0901.sys'),
            cat: path.join(tapDir, 'tap0901.cat')
        };
    }

    /**
     * 安装 TAP 驱动（从 OpenVPN 目录提取）
     */
    static async installTapDriver() {
        const ovpnPath = this.findOpenVPN();
        if (!ovpnPath) {
            throw new Error('OpenVPN 未安装。请先安装 OpenVPN 或运行 wrtc-neo ovpn-install');
        }

        const ovpnDir = path.dirname(ovpnPath); // .../bin/
        const driverDir = path.join(ovpnDir, '..', 'driver');

        // 查找 tap-windows 驱动
        const tapDirs = [
            path.join(ovpnDir, '..', 'tap-windows'),
            path.join(ovpnDir, '..', 'tap-windows6'),
            path.join(driverDir, 'tap-windows6'),
            driverDir
        ];

        let tapDriverDir = null;
        for (const d of tapDirs) {
            if (fs.existsSync(path.join(d, 'OemVista.inf'))) {
                tapDriverDir = d;
                break;
            }
        }

        if (!tapDriverDir) {
            throw new Error('找不到 TAP 驱动文件。请确保 OpenVPN 完整安装。');
        }

        // 安装驱动
        const tapInstall = path.join(ovpnDir, 'tapinstall.exe');
        const cmd = tapInstall && fs.existsSync(tapInstall)
            ? `"${tapInstall}" install "${path.join(tapDriverDir, 'OemVista.inf')}" tap0901`
            : `pnputil /add-driver "${path.join(tapDriverDir, 'OemVista.inf')}" /install`;

        console.log('[OvpnAdapter] Installing TAP driver...');
        execSync(cmd, { encoding: 'utf8', stdio: 'pipe' });
        console.log('[OvpnAdapter] TAP driver installed.');
    }

    // ============================================================
    // 静态密钥
    // ============================================================
    generateStaticKey() {
        if (fs.existsSync(this._staticKeyFile)) {
            this._staticKey = fs.readFileSync(this._staticKeyFile, 'utf8');
            return this._staticKey;
        }

        const key = `#
# 2048 bit OpenVPN static key
# Generated by wrtc-neo
#
-----BEGIN OpenVPN Static key V1-----
${this._generateKeyBlock()}
-----END OpenVPN Static key V1-----
`;
        fs.writeFileSync(this._staticKeyFile, key);
        this._staticKey = key;
        return key;
    }

    getStaticKey() {
        if (!this._staticKey) {
            if (fs.existsSync(this._staticKeyFile)) {
                this._staticKey = fs.readFileSync(this._staticKeyFile, 'utf8');
            }
        }
        return this._staticKey;
    }

    setStaticKey(key) {
        this._staticKey = key;
        fs.writeFileSync(this._staticKeyFile, key);
    }

    _generateKeyBlock() {
        const lines = [];
        for (let i = 0; i < 16; i++) {
            const bytes = crypto.randomBytes(16);
            const hex = bytes.toString('hex').match(/.{1,2}/g).join(' ');
            lines.push(hex);
        }
        return lines.join('\n');
    }

    // ============================================================
    // 生成 OpenVPN 配置
    // ============================================================
    _generateServerConfig(localIP) {
        const key = this.getStaticKey() || this.generateStaticKey();
        const config = `
# wrtc-neo OpenVPN Server Config
dev tun
dev-type tap
proto udp
port ${this._port}
mode server
tls-server
ifconfig ${localIP} 255.255.255.0
ifconfig-pool ${this._subnet}.10 ${this._subnet}.50 255.255.255.0
topology subnet
secret "${this._staticKeyFile.replace(/\\/g, '\\\\')}" 0
keepalive 10 60
persist-tun
persist-key
verb 1
mute 5
`;
        const configPath = path.join(this._configDir, 'server.ovpn');
        fs.writeFileSync(configPath, config);
        return configPath;
    }

    _generateClientConfig(serverHost, serverPort, localIP) {
        const key = this.getStaticKey();
        if (!key) throw new Error('No static key. Run startServer() first to generate key.');

        const config = `
# wrtc-neo OpenVPN Client Config
dev tun
dev-type tap
proto udp
remote ${serverHost} ${serverPort}
resolv-retry infinite
nobind
persist-tun
persist-key
secret "${this._staticKeyFile.replace(/\\/g, '\\\\')}" 1
ifconfig ${localIP} 255.255.255.0
keepalive 10 60
verb 1
mute 5
`;
        const configPath = path.join(this._configDir, 'client.ovpn');
        fs.writeFileSync(configPath, config);
        return configPath;
    }

    // ============================================================
    // 启动 / 停止
    // ============================================================
    /**
     * 主机模式：启动 OpenVPN server
     */
    async startServer() {
        if (this._state !== 'stopped') {
            throw new Error(`OvpnAdapter is already ${this._state}`);
        }

        const ovpnPath = OvpnAdapter.findOpenVPN();
        if (!ovpnPath) {
            throw new Error('OpenVPN 未安装。请运行 wrtc-neo ovpn-install');
        }

        this._mode = 'server';
        this._localIP = `${this._subnet}.1`;
        this._configPath = this._generateServerConfig(this._localIP);

        this._state = 'starting';
        this.emit('starting', { mode: 'server', ip: this._localIP });

        this._process = spawn(ovpnPath, ['--config', this._configPath], {
            stdio: ['ignore', 'pipe', 'pipe'],
            windowsHide: true
        });

        this._setupProcessListeners();

        return new Promise((resolve, reject) => {
            // 等 OpenVPN 启动完成
            const timeout = setTimeout(() => {
                if (this._state === 'starting') {
                    this._state = 'running';
                    this.emit('ready', { mode: 'server', ip: this._localIP, port: this._port });
                    resolve({ mode: 'server', ip: this._localIP, port: this._port });
                }
            }, 5000);

            this._process.stdout.on('data', (data) => {
                const text = data.toString();
                // OpenVPN 初始化完成
                if (text.includes('Initialization Sequence Completed')) {
                    clearTimeout(timeout);
                    this._state = 'running';
                    this.emit('ready', { mode: 'server', ip: this._localIP, port: this._port });
                    resolve({ mode: 'server', ip: this._localIP, port: this._port });
                }
            });

            this._process.on('error', (err) => {
                clearTimeout(timeout);
                this._state = 'stopped';
                reject(err);
            });

            this._process.on('exit', (code) => {
                clearTimeout(timeout);
                if (this._state === 'starting') {
                    this._state = 'stopped';
                    reject(new Error(`OpenVPN exited with code ${code}`));
                }
            });
        });
    }

    /**
     * 客户端模式：连接到主机
     */
    async startClient(serverHost, serverPort, localIP) {
        if (this._state !== 'stopped') {
            throw new Error(`OvpnAdapter is already ${this._state}`);
        }

        const ovpnPath = OvpnAdapter.findOpenVPN();
        if (!ovpnPath) {
            throw new Error('OpenVPN 未安装。请运行 wrtc-neo ovpn-install');
        }

        this._mode = 'client';
        this._localIP = localIP || `${this._subnet}.10`;
        this._configPath = this._generateClientConfig(serverHost, serverPort, this._localIP);

        this._state = 'starting';
        this.emit('starting', { mode: 'client', server: `${serverHost}:${serverPort}`, ip: this._localIP });

        this._process = spawn(ovpnPath, ['--config', this._configPath], {
            stdio: ['ignore', 'pipe', 'pipe'],
            windowsHide: true
        });

        this._setupProcessListeners();

        return new Promise((resolve, reject) => {
            const timeout = setTimeout(() => {
                if (this._state === 'starting') {
                    this._state = 'running';
                    this.emit('ready', { mode: 'client', ip: this._localIP, server: serverHost });
                    resolve({ mode: 'client', ip: this._localIP });
                }
            }, 8000);

            this._process.stdout.on('data', (data) => {
                const text = data.toString();
                if (text.includes('Initialization Sequence Completed')) {
                    clearTimeout(timeout);
                    this._state = 'running';
                    this.emit('ready', { mode: 'client', ip: this._localIP, server: serverHost });
                    resolve({ mode: 'client', ip: this._localIP });
                }
            });

            this._process.on('error', (err) => {
                clearTimeout(timeout);
                this._state = 'stopped';
                reject(err);
            });

            this._process.on('exit', (code) => {
                clearTimeout(timeout);
                if (this._state === 'starting') {
                    this._state = 'stopped';
                    reject(new Error(`OpenVPN exited with code ${code}`));
                }
            });
        });
    }

    /**
     * 停止 OpenVPN
     */
    stop() {
        if (this._process) {
            try {
                // 发送 SIGTERM（OpenVPN 会优雅退出）
                this._process.kill('SIGTERM');
                setTimeout(() => {
                    if (this._process && !this._process.killed) {
                        this._process.kill('SIGKILL');
                    }
                }, 3000);
            } catch (e) { /* already dead */ }
            this._process = null;
        }
        this._state = 'stopped';
        this._mode = 'none';
        this.emit('stopped');
    }

    _setupProcessListeners() {
        if (!this._process) return;

        this._process.stdout.on('data', (data) => {
            this.emit('log', { level: 'info', text: data.toString().trim() });
        });

        this._process.stderr.on('data', (data) => {
            this.emit('log', { level: 'error', text: data.toString().trim() });
        });

        this._process.on('exit', (code) => {
            this._state = 'stopped';
            this._process = null;
            this.emit('exit', { code });
        });

        this._process.on('error', (err) => {
            this.emit('error', err);
        });
    }

    // ============================================================
    // 获取 TAP 网卡信息
    // ============================================================
    getTapAdapterName() {
        if (os.platform() !== 'win32') return null;
        try {
            // 获取 TAP-Windows 适配器名
            const result = execSync(
                'powershell -Command "Get-NetAdapter | Where-Object { $_.InterfaceDescription -like \'*TAP*\' } | Select-Object -First 1 -ExpandProperty Name"',
                { encoding: 'utf8', timeout: 5000 }
            ).trim();
            return result || null;
        } catch (e) {
            return null;
        }
    }

    getTapAdapterIP() {
        if (os.platform() !== 'win32') return null;
        try {
            const name = this.getTapAdapterName();
            if (!name) return null;
            const result = execSync(
                `powershell -Command "(Get-NetIPAddress -InterfaceAlias '${name}' -AddressFamily IPv4).IPAddress"`,
                { encoding: 'utf8', timeout: 5000 }
            ).trim();
            return result || null;
        } catch (e) {
            return null;
        }
    }

    // ============================================================
    // 状态
    // ============================================================
    get mode() { return this._mode; }
    get state() { return this._state; }
    get localIP() { return this._localIP; }
    get port() { return this._port; }
    get isRunning() { return this._state === 'running'; }

    getStatus() {
        return {
            mode: this._mode,
            state: this._state,
            localIP: this._localIP,
            port: this._port,
            tapAdapter: this.getTapAdapterName(),
            tapIP: this.getTapAdapterIP(),
            openvpnInstalled: OvpnAdapter.isInstalled(),
            openvpnPath: OvpnAdapter.findOpenVPN()
        };
    }
}

OvpnAdapter.OVPN_DIR = DEFAULT_OVPN_DIR;
OvpnAdapter.STATIC_KEY_FILE = STATIC_KEY_FILE;

module.exports = OvpnAdapter;